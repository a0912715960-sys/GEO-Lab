import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { tool } from './tools.mjs';

export const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const output = path.dirname(root);
const hash = (bytes) => createHash('sha256').update(bytes).digest('hex');
export function sourceHashes() {
  return Object.fromEntries(
    fs
      .readdirSync(path.join(root, 'src'))
      .sort()
      .map((name) => ['src/' + name, hash(fs.readFileSync(path.join(root, 'src', name)))]),
  );
}
export async function build() {
  const esbuild = tool('esbuild');
  const built = await esbuild.build({
    entryPoints: [path.join(root, 'src/ui.mjs')],
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: 'es2022',
    write: false,
    minify: false,
    banner: { js: '// GENERATED by scripts/build.mjs from src/. Do not edit this bundle.' },
  });
  const bundle = built.outputFiles[0].text,
    bundleSha256 = hash(bundle),
    dist = path.join(root, 'dist');
  if (
    path.resolve(dist) !== path.resolve(root, 'dist') ||
    !fs.existsSync(path.join(root, 'src/platform.mjs'))
  )
    throw new Error('Refusing unexpected build output path');
  fs.rmSync(dist, { recursive: true, force: true });
  fs.mkdirSync(dist, { recursive: true });
  const read = (name) => fs.readFileSync(path.join(root, 'src', name), 'utf8');
  const bootstrap = read('bootstrap.js'),
    css = read('style.css');
  const fallback =
    '<main class="startup"><h1>GEO SIGNAL · 智能监测与优化平台</h1><p>如果一直看到这段说明，当前预览没有执行脚本。请下载 HTML 文件，用 Edge 或 Chrome 打开。</p><noscript><p>此处 JavaScript 被禁用。</p></noscript></main>';
  const html = (config, inline) =>
    `<!doctype html><html lang="zh-CN"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="geo-bundle-sha256" content="${bundleSha256}"><title>GEO SIGNAL · 智能监测与优化平台</title>${inline ? '<style>' + css + '</style>' : '<link rel="stylesheet" href="./style.css">'}</head><body><div id="app">${fallback}</div><div id="toast" role="status"></div>${inline ? '<script>window.GEO_ASSETS=' + JSON.stringify(config) + ';</script><script>' + bootstrap + '</script><script data-geo-bundle>' + bundle + '</script>' : '<script src="./bootstrap.js"></script><script src="./entry.js"></script>'}</body></html>`;
  fs.writeFileSync(path.join(dist, 'app.js'), bundle);
  fs.writeFileSync(path.join(dist, 'bootstrap.js'), bootstrap);
  fs.writeFileSync(path.join(dist, 'style.css'), css);
  fs.writeFileSync(
    path.join(dist, 'entry.js'),
    "if(location.protocol==='file:')location.replace(new URL('../OFFLINE-DEMO.html',location.href));else{const script=document.createElement('script');script.src='./app.js';script.onerror=()=>window.__geoStartupFail('应用文件加载失败');document.head.append(script);}\n",
  );
  fs.writeFileSync(path.join(dist, 'index.html'), html({}, false));
  fs.writeFileSync(
    path.join(root, 'OFFLINE-DEMO.html'),
    html({ docsBase: '', packageUrl: 'README.md' }, true),
  );
  fs.writeFileSync(
    path.join(output, 'GEO-Growth-Demo.html'),
    html({ docsBase: 'geo-growth/', packageUrl: 'GEO-Growth-Lab.zip' }, true),
  );
  const manifest = {
    schemaVersion: 1,
    bundler: 'esbuild',
    bundlerVersion: esbuild.version,
    bundleSha256,
    inputs: sourceHashes(),
    generated: ['dist/app.js', 'dist/index.html', 'OFFLINE-DEMO.html', '../GEO-Growth-Demo.html'],
  };
  fs.writeFileSync(path.join(dist, 'build.json'), JSON.stringify(manifest, null, 2));
  console.log(`Built one shared bundle: ${bundleSha256}`);
  return { html, bundleSha256 };
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  await build();
